export function normalizeCircuit(c: string): string {
  return c.replace(/\s+/g, "").toUpperCase().split("/")[0].replace(/[()+-]/g, "");
}

export function sameCircuit(a: string, b: string): boolean {
  const na = normalizeCircuit(a);
  const nb = normalizeCircuit(b);
  if (!na || !nb || na === "---" || nb === "---") return false;
  if (na === nb) return true;
  const fa = na.match(/^\d+/)?.[0];
  const fb = nb.match(/^\d+/)?.[0];
  const ta = na.replace(/^\d+/, "");
  const tb = nb.replace(/^\d+/, "");
  if (fa && fa === fb && (na === fa || nb === fb || na.includes(nb) || nb.includes(na))) return true;
  if (fa && fa === fb && ta && tb && (ta.startsWith(tb) || tb.startsWith(ta))) return true;
  return false;
}

export type PinHit = {
  connector: Connector;
  pin: Pin;
};

export function findCircuitHits(circuit: string): PinHit[] {
  if (!circuit || circuit.includes("---")) return [];
  const hits: PinHit[] = [];
  for (const c of connectors) {
    for (const p of c.pins) {
      if (sameCircuit(p.circuit, circuit) || p.circuit.toUpperCase().includes(circuit.toUpperCase())) {
        hits.push({ connector: c, pin: p });
      }
    }
  }
  return hits;
}
